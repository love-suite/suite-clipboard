import Foundation

/// Pasteboard type identifiers the clipboard history reads, as strings so this module needs no AppKit.
public enum PasteboardType {
    public static let plainText = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let rtfd = "com.apple.flat-rtfd"
    public static let html = "public.html"
    public static let fileURL = "public.file-url"
    public static let url = "public.url"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let jpeg = "public.jpeg"
    public static let heic = "public.heic"

    /// Markers from nspasteboard.org: passwords and other secrets, content that is only passing
    /// through, and content an app made up rather than the user copying it.
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    /// The bundle identifier of the app that wrote the pasteboard, when it says so.
    public static let source = "org.nspasteboard.source"
    /// Set by Universal Clipboard on what was copied on another device (an iPhone, an iPad, another
    /// Mac). It doesn't say which.
    public static let remoteClipboard = "com.apple.is-remote-clipboard"

    public static let images = [png, tiff, jpeg, heic]
    static let richText = [rtf, rtfd, html]
}

/// What was on the pasteboard: one dictionary per pasteboard item, from type identifier to data, so
/// several copied files or a rich text with its plain version all come back as they were.
public struct PasteboardSnapshot: Codable, Equatable, Sendable {
    public var items: [[String: Data]]

    public init(items: [[String: Data]]) {
        self.items = items
    }

    public var types: Set<String> {
        Set(items.flatMap(\.keys))
    }

    /// The first item's data of that type.
    public func data(_ type: String) -> Data? {
        items.lazy.compactMap { $0[type] }.first
    }

    public func string(_ type: String) -> String? {
        data(type).flatMap { String(data: $0, encoding: .utf8) }
    }

    public var byteCount: Int {
        items.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } }
    }

    public var isEmpty: Bool {
        items.allSatisfy(\.isEmpty)
    }
}

/// One entry of the history. Its pasteboard contents are stored apart (see `ClipboardStore`), so the
/// history itself stays small even with pictures in it.
public struct ClipItem: Codable, Equatable, Identifiable, Sendable {
    public enum Kind: String, Codable, Sendable {
        case text, richText, link, image, files
    }

    public var id: UUID
    public var kind: Kind
    /// When it was last copied.
    public var date: Date
    /// What the list shows and search looks into: the text, the link, or one file path per line.
    /// Empty for pictures.
    public var text: String
    /// Two copies of the same thing have the same fingerprint, so the history keeps one of them.
    public var fingerprint: String
    /// The app it was copied from.
    public var sourceApp: String?
    public var sourceName: String?
    public var byteCount: Int
    /// The text found in a picture, so search finds screenshots by what they say. Nil until the
    /// picture has been read.
    public var recognizedText: String?
    /// Copied on another device and received through Universal Clipboard. Optional so histories
    /// saved before it still load.
    public var copiedOnOtherDevice: Bool?

    public var isFromOtherDevice: Bool { copiedOnOtherDevice == true }

    public init(id: UUID = UUID(), kind: Kind, date: Date = Date(), text: String,
                fingerprint: String, sourceApp: String? = nil, sourceName: String? = nil, byteCount: Int = 0) {
        self.id = id
        self.kind = kind
        self.date = date
        self.text = text
        self.fingerprint = fingerprint
        self.sourceApp = sourceApp
        self.sourceName = sourceName
        self.byteCount = byteCount
    }

    /// The copied files, for a `.files` item.
    public var fileURLs: [URL] {
        kind == .files ? text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) } : []
    }

    /// One line for the list: the first non-empty line of the text, or the file names.
    public var title: String {
        switch kind {
        case .files:
            return fileURLs.map(\.lastPathComponent).joined(separator: ", ")
        case .image:
            return "Picture"
        default:
            let line = text.split(whereSeparator: \.isNewline)
                .first { !$0.trimmingCharacters(in: .whitespaces).isEmpty }
            return line.map { $0.trimmingCharacters(in: .whitespaces) } ?? text
        }
    }
}
