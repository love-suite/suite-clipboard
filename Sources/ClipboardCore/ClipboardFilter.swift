import Foundation
import ClipboardSettings

/// What the history must not record: what password managers mark as secret or passing, and what is
/// copied in apps the user chose to ignore.
public struct ClipboardFilter: Equatable, Sendable {
    /// Markers apps put on the pasteboard to say "don't keep this": nspasteboard.org's, and older
    /// ones some password managers and utilities still write.
    public static let privateTypes: Set<String> = [
        PasteboardType.concealed,
        PasteboardType.transient,
        PasteboardType.autoGenerated,
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Apple's password apps, ignored until the user says otherwise.
    public static var defaultIgnoredApps: [String] { ClipboardSettings.defaultIgnoredApps }

    public var ignoredApps: Set<String>

    public init(ignoredApps: some Sequence<String> = defaultIgnoredApps) {
        self.ignoredApps = Set(ignoredApps)
    }

    /// Whether a pasteboard change should go into the history. `frontmostApp` is the app in front when
    /// it was seen, used when the pasteboard doesn't name its source.
    public func shouldRecord(_ snapshot: PasteboardSnapshot, frontmostApp: String?) -> Bool {
        shouldRecord(types: snapshot.types, source: Self.source(of: snapshot, frontmostApp: frontmostApp))
    }

    /// The same check from the pasteboard's types alone, so a secret's data is never even read.
    public func shouldRecord(types: some Sequence<String>, source: String?) -> Bool {
        guard Set(types).isDisjoint(with: Self.privateTypes) else { return false }
        if let source, ignoredApps.contains(source) { return false }
        return true
    }

    /// The app it was copied from: the one the pasteboard names, or else the one in front.
    public static func source(of snapshot: PasteboardSnapshot, frontmostApp: String?) -> String? {
        if let named = snapshot.string(PasteboardType.source)?.trimmingCharacters(in: .whitespacesAndNewlines),
           !named.isEmpty {
            return named
        }
        return frontmostApp
    }
}

extension ClipboardSettings {
    /// What the history records and what it leaves out, from these settings.
    public var filter: ClipboardFilter {
        ClipboardFilter(ignoredApps: ignoredApps)
    }
}
